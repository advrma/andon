// Rebuilds compositions/captions.html from the voice word timings in assets/vo.
// Groups are fixed below (line, first word, last word); times come from the TTS words.
import { readFileSync, writeFileSync } from "node:fs";

const LINE_START = [0.3, 3.4, 16.0, 33.7, 41.6, 49.5];
// 3–6 words a group, broken at clause ends; the three cheap fixes are three groups, like the stack on screen.
const GROUPS = [
  [1, 0, 2], [1, 3, 7],
  [2, 0, 3],
  [3, 0, 4], [3, 5, 7],
  [4, 0, 6],
  [5, 0, 4], [5, 5, 9],
  [6, 0, 5], [6, 6, 8], [6, 9, 12],
];
const HOLD = 0.35;
const words = (n) => JSON.parse(readFileSync(`assets/vo2/${String(n).padStart(2, "0")}.words.json`, "utf8"));

const groups = GROUPS.map(([line, a, b]) => {
  const w = words(line);
  const t0 = LINE_START[line - 1];
  return { text: w.slice(a, b + 1).map((x) => x.text).join(" "), start: t0 + w[a].start - 0.05, end: t0 + w[b].end + HOLD };
});
groups.forEach((g, i) => {
  const next = groups[i + 1];
  if (next && g.end > next.start - 0.05) g.end = next.start - 0.05;
  if (!next) g.end = Math.min(g.end, 59.5);
});

const items = groups
  .map((g, i) => {
    const id = `cap${String(i + 1).padStart(2, "0")}`;
    const start = g.start.toFixed(2);
    const dur = (g.end - g.start).toFixed(2);
    return `    <div id="${id}" class="cap clip" data-layout-allow-overlap data-layout-allow-occlusion data-start="${start}" data-duration="${dur}" data-track-index="0"><span>${g.text}</span></div>`;
  })
  .join("\n");

const html = `<template>
  <style>
    @font-face {
      font-family: "Instrument Sans";
      src: url("assets/fonts/InstrumentSans.woff2") format("woff2");
      font-weight: 400 600;
    }
    #root {
      position: absolute;
      inset: 0;
      font-family: "Instrument Sans", system-ui, sans-serif;
      pointer-events: none;
    }
    .cap {
      position: absolute;
      left: 0;
      right: 0;
      bottom: 108px;
      text-align: center;
      overflow: visible;
    }
    .cap > span {
      display: inline-block;
      padding: 14px 28px;
      border-radius: 12px;
      background: #fff;
      border: 1px solid #e4e4e0;
      font-size: 36px;
      font-weight: 500;
      line-height: 1.2;
      color: #16181d;
      white-space: nowrap;
    }
  </style>

  <div id="root" data-composition-id="captions" data-width="1920" data-height="1080">
    <!-- Generated by tools/build-captions.mjs from assets/vo2/*.words.json. One group at a time, timed to the voice. -->
${items}
  </div>

  <script>
    const tl = gsap.timeline({ paused: true });
    // Words arrive light grey to ink, 70 ms apart; the group fades 120 ms before its end.
    document.querySelectorAll("#root .cap").forEach((cap) => {
      const start = parseFloat(cap.dataset.start);
      const end = start + parseFloat(cap.dataset.duration);
      const box = cap.querySelector("span");
      const words = box.textContent.split(" ");
      box.textContent = "";
      words.forEach((w, i) => {
        const s = document.createElement("span");
        s.className = "w";
        s.textContent = (i ? " " : "") + w;
        box.appendChild(s);
      });
      const ws = box.querySelectorAll(".w");
      tl.fromTo(box, { opacity: 0 }, { opacity: 1, duration: 0.12, ease: "power2.out" }, start);
      tl.fromTo(ws, { color: "#b9bbc0" }, { color: "#16181d", duration: 0.12, ease: "power2.out", stagger: 0.07 }, start);
      tl.to(box, { opacity: 0, duration: 0.12, ease: "power2.in" }, end - 0.12);
    });
    window.__timelines = window.__timelines || {};
    window.__timelines["captions"] = tl;
    tl.seek(0);
  </script>
</template>
`;
writeFileSync("compositions/captions.html", html);
groups.forEach((g, i) => console.log(String(i + 1).padStart(2, "0"), g.start.toFixed(2), "->", g.end.toFixed(2), g.text));
